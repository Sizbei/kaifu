/** The exemplar block for one register, ready to paste into a system prompt. */
export function exemplarBlock(id: RegisterId): string {
  return EXEMPLARS.map(
    (ex, i) => `【例${i + 1}: ${ex.reader}】\n${ex.byRegister[id]}`,
  ).join("\n\n");
}
